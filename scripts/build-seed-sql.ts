// Generates supabase/seed.sql from data/*.ts.  Run:  npm run seed:sql
// The output is SEED DATA. It is safe to run more than once (skips existing names).
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { SEED_FOODS } from "../data/foods";
import { SEED_EXERCISES } from "../data/exercises";
import { seedFoodToRow } from "../data/toRows";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : `'{}'::text[]`);

const foodRows = SEED_FOODS.map(seedFoodToRow).map(
  (r) =>
    `  (${[
      q(r.name), q(r.category), q(r.diet_type), r.serving_size_g, q(r.serving_desc), r.kcal, r.protein_g,
      r.carbs_g, r.fat_g, r.fibre_g, arr(r.allergens), arr(r.roles), r.price_inr ?? "null", q(r.source), "false",
    ].join(", ")})`,
);

const exRows = SEED_EXERCISES.map(
  (x) =>
    `  (${[
      q(x.name), q(x.target_muscle), q(x.equipment), q(x.difficulty), x.default_sets, q(x.default_reps),
      x.default_rest_sec, q(x.instructions),
    ].join(", ")})`,
);

const sql = `-- =====================================================================
-- SEED DATA — generated by scripts/build-seed-sql.ts. Do not edit by hand.
-- ${SEED_FOODS.length} foods (ALL marked verified = false — staff must check
-- values against IFCT 2017 / USDA FoodData Central) and ${SEED_EXERCISES.length} exercises.
-- Safe to run more than once: rows whose name already exists are skipped.
-- =====================================================================

insert into public.foods
  (name, category, diet_type, serving_size_g, serving_desc, kcal, protein_g, carbs_g, fat_g, fibre_g,
   allergens, roles, price_inr, source, verified)
values
${foodRows.join(",\n")}
on conflict ((lower(name))) do nothing;

insert into public.exercises
  (name, target_muscle, equipment, difficulty, default_sets, default_reps, default_rest_sec, instructions)
values
${exRows.join(",\n")}
on conflict ((lower(name))) do nothing;
`;

const out = join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(out, sql, "utf8");
console.log(`Wrote ${out}: ${SEED_FOODS.length} foods, ${SEED_EXERCISES.length} exercises`);
